def _trim(font: dict) -> dict:
    """Each glyph as (width, rows of '#' columns), empty edge columns trimmed so the face is proportional."""
    out = {}
    for ch, rows in font.items():
        cols = [i for i in range(max(len(r) for r in rows)) if any(i < len(r) and r[i] == "#" for r in rows)]
        lo, hi = (min(cols), max(cols)) if cols else (0, -1)
        out[ch] = (hi - lo + 1, [[i - lo for i in range(len(r)) if r[i] == "#"] for r in rows])
    return out


G57, G35 = _trim(F57), _trim(F35)
FONTS = {"57": (G57, 7, 3), "35": (G35, 5, 2)}  # glyphs, cap height, space width

# What a character the faces lack is drawn as, before an accent is dropped: typography straightened,
# the banned dashes turned into hyphens, and a few marks into the nearest the faces have.
FOLDS = {
    "‘": "'", "’": "'", "‚": "'", "‛": "'", "′": "'",
    "“": '"', "”": '"', "„": '"', "″": '"',
    "‐": "-", "‑": "-", "‒": "-", "–": "-", "—": "-", "―": "-", "−": "-",
    "…": "...", "×": "x", "•": "·", " ": " ", " ": " ", " ": " ",
    "«": "<", "»": ">", "←": "<", "→": ">",
    "~": "-", "{": "(", "}": ")", "\\": "/", "^": "'", "`": "'", "$": "S",
}
# Every character a line was drawn without, since a caller last cleared it.
MISSING: set[str] = set()


def fold(s: str, font: str = "57") -> str:
    """`s` as the face can draw it: typography straightened, accents dropped, a small-capital face's text
    upper-cased, and any character still missing drawn as `?` and recorded in MISSING."""
    glyphs = FONTS[font][0]
    out = []
    for ch in str(s):
        for c in FOLDS.get(ch, ch):
            if font == "35":
                c = c.upper()
            if c == " " or c in glyphs:
                out.append(c)
                continue
            bare = "".join(b for b in unicodedata.normalize("NFKD", c) if not unicodedata.combining(b))
            bare = bare.upper() if font == "35" else bare
            if bare and all(b == " " or b in glyphs for b in bare):
                out.append(bare)
            else:
                MISSING.add(c)
                out.append("?")
    return "".join(out)


def measure(s: str, font: str = "57", scale: int = 1, track: int = 1) -> int:
    """How wide `s` is set, in pixels of the canvas: font pixels times `scale`, `track` between letters."""
    glyphs, _, space = FONTS[font]
    s = fold(s, font)
    w = 0
    for i, ch in enumerate(s):
        gw = space if ch == " " else glyphs[ch][0]
        w += gw * scale + (track * scale if i < len(s) - 1 else 0)
    return w


def _pieces(word: str) -> list[str]:
    """A word split after each hyphen, slash, underscore or dot: where it may break when it must."""
    out, cur = [], ""
    for ch in word:
        cur += ch
        if ch in "-/_." and len(cur) > 1:
            out.append(cur)
            cur = ""
    if cur:
        out.append(cur)
    return out


def wrap(s: str, maxw: int, font: str = "57", scale: int = 1, track: int = 1) -> list[str]:
    """`s` broken into lines no wider than `maxw`, at spaces. A word wider than a line breaks after its
    hyphens, slashes, underscores and dots, packed as words are, and only a piece that cannot fit on a
    line of its own is cut where it must be."""
    def fits(t: str) -> bool:
        return measure(t, font, scale, track) <= maxw

    lines, cur = [], ""
    for word in fold(s, font).split():
        trial = f"{cur} {word}" if cur else word
        if fits(trial):
            cur = trial
            continue
        if fits(word):
            lines.append(cur)
            cur = word
            continue
        for i, piece in enumerate(_pieces(word)):
            trial = cur + (" " if i == 0 and cur else "") + piece
            if fits(trial):
                cur = trial
                continue
            if cur:
                lines.append(cur)
            while not fits(piece):
                n = 1
                while n < len(piece) and fits(piece[:n + 1]):
                    n += 1
                lines.append(piece[:n])
                piece = piece[n:]
            cur = piece
    if cur:
        lines.append(cur)
    return lines


def clip(s: str, maxw: int, font: str = "57", scale: int = 1, track: int = 1) -> str:
    """`s` cut to fit `maxw`, ending in an ellipsis when anything had to go."""
    s = fold(s, font)
    if measure(s, font, scale, track) <= maxw:
        return s
    while s and measure(s.rstrip(" ,.;:-") + "...", font, scale, track) > maxw:
        s = s[:-1]
    return s.rstrip(" ,.;:-") + "..."


def fit(s: str, maxw, font: str = "57", scales: tuple = (4, 3, 2), rows: int = 2) -> tuple[int, list[str]]:
    """The biggest of `scales` a title can be set at, on one line if it fits and on up to `rows` if it
    must, and its lines. `maxw` is the room, or a map of each scale to its room. At the smallest scale
    the title wraps however it has to."""
    room = maxw if isinstance(maxw, dict) else {sc: maxw for sc in scales}
    for scale in scales:
        if measure(s, font, scale) <= room[scale]:
            return scale, [fold(s, font)]
    for scale in scales:
        lines = wrap(s, room[scale], font, scale)
        if len(lines) <= rows:
            return scale, lines
    return scales[-1], wrap(s, room[scales[-1]], font, scales[-1])
